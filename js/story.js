// 关卡数值（hp/spawn/maxAlive/ammo/ammoPack/bossHp）和章节奖励由扩写时的脚本按难度曲线统一生成，调平衡可以直接改
//
// 数据结构说明：
// CAST：人物表 { 名字: { color: 名字颜色, desc: 一句话介绍 } }
// CHAPTERS：章节数组，每章包含：
//   title   章节名
//   zone    地图编号 0~4（郊外小镇 / 废弃商场 / 市立医院 / 军事基地 / 病毒研究所）
//   reward  整章通关奖励 { scrap: 废料, survivor: 加入的同伴 }
//   intro   章节开场对白，在第 1 关开始前播放
//   outro   章节结尾对白，在第 3 关结束后播放
//   stages  3 个关卡对象
// 关卡对象：
//   title   编号 + 关卡名
//   type    'collect' 收集 | 'defend' 坚守 | 'rescue' 救援护送 | 'boss' 首领战
//   intro   关卡开场对白；outro 关卡结束对白
//   radio   关卡中的无线电字幕 [进度 0~1, 说话人, 台词]
//   hp / spawn / maxAlive / ammo / ammoPack  丧尸血量倍率 / 每秒刷怪 / 同屏上限 / 初始弹药 / 弹药箱子弹数
//   按类型选填：obj（collect）、hold（defend）、npc（rescue）、bossName + bossHp（boss）
//   enemies 可选，本关额外出现的新敌人：
//           'exploder' 自爆者 | 'spitter' 喷吐者 | 'screamer' 尖叫者 | 'armored' 护甲丧尸
//
// 对白格式：
//   [说话人, 台词]                       普通台词；说话人为空字符串 = 旁白
//   [说话人, 台词, { if: 'flag' }]       条件台词：标记为真时才显示
//   [说话人, 台词, { if: '!flag' }]      条件台词：标记为假时才显示
//   ['?', 提示语, [选项1, 选项2]]         选择；选项格式：
//     { text: 选项文字, set: { 标记: true }, reply: [[说话人, 台词], ...], gain: { scrap / food } 可选 }
//
// 剧情标记（全部由主线选择设置）：
//   takeSupplies   第一章：带走诊所剩下的物资（额外废料）
//   helpTown       第一章：把弹药和药品留给青石镇的镇民
//   trustJie       第二章：相信阿杰，让他自己保管门禁卡
//   doubtJie       第二章：收走阿杰的门禁卡，对他有所提防
//   saveCivilians  第三章：先把医院五楼的七个病人送出去
//   rushZero       第三章：不管病人，直接去追零号病人（额外废料）
//   takeSample     第三章：把零号病人的血样带走
//   burnSample     第三章：当场烧掉零号病人的血样
//   spareQin       第四章：给垂死的秦锋止血，留他一命
//   leftQin        第四章：丢下秦锋，转身离开
//   publishData    最终章：把启明的全部数据公之于众
//   handToArmy     最终章：把数据交给周队长的上级
//
// 结局（ENDINGS，按顺序判断）：
//   真相大白 = publishData + saveCivilians；余烬 = publishData；黎明 = handToArmy + saveTang；默认 = 沉默之城

